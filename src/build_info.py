"""Which build is this? The commit a binary was built from, stamped at build time.

Found the hard way: a local dev build reported itself as "3.1.0" -- in the About
box and in the exe's ProductVersion -- while missing a fix that shipped in the
real 3.1.0. Telling the two apart took unpacking the exe. APP_VERSION alone
can't say it: it is bumped once per release, and every build in between wears
the same number.

So the PyInstaller spec calls write_stamp() before analysis, which records the
git commit, whether the tree had uncommitted changes, and whether HEAD is
exactly the release tag for APP_VERSION, into ``src/_build_info.py`` (git-
ignored). A frozen build reads that; running from source asks git directly.

APP_VERSION itself is untouched -- the update check compares it against the
release tag, so it must stay a bare version. Only the *displayed* label grows.

Qt-free and app-settings-free so the spec can import it at build time.
"""

from __future__ import annotations

import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

STAMP_MODULE = "_build_info"
_REPO_ROOT = Path(__file__).resolve().parent.parent


@dataclass(frozen=True)
class BuildInfo:
    commit: str | None   # short SHA, None when unknown
    dirty: bool          # built from a tree with uncommitted changes
    release: bool        # HEAD was exactly the v<APP_VERSION> tag, clean


def version_label(version: str, info: BuildInfo) -> str:
    """What the About box shows.

    - release build:  ``3.1.0 (3ec0425)``
    - anything else:  ``3.1.0+dev.1d4a1cc`` (``.dirty`` appended if the tree
      had local changes)
    - no commit known: ``3.1.0+dev`` -- never a bare version, because a bare
      version is exactly the claim that couldn't be trusted.
    """
    if info.release and info.commit and not info.dirty:
        return f"{version} ({info.commit})"
    label = f"{version}+dev"
    if info.commit:
        label += f".{info.commit}"
    if info.dirty:
        label += ".dirty"
    return label


def _git(args: list[str], cwd: Path) -> str | None:
    try:
        out = subprocess.run(
            ["git", *args], cwd=str(cwd), capture_output=True, text=True,
            timeout=5,
            # No console flash when the frozen Windows app never calls this,
            # but a from-source run on Windows would otherwise pop one.
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 else None


def from_git(version: str, cwd: Path = _REPO_ROOT, env=None) -> BuildInfo:
    """Read the build identity from the git checkout at ``cwd``."""
    env = os.environ if env is None else env
    commit = _git(["rev-parse", "--short=7", "HEAD"], cwd)
    if commit is None:
        return BuildInfo(None, False, False)
    # --untracked-files=no: a stray scratch file is not a code change, and
    # build output (dist/, build/) must not mark every build dirty.
    status = _git(["status", "--porcelain", "--untracked-files=no"], cwd)
    dirty = bool(status)
    tag = f"v{version}"
    exact = _git(["describe", "--tags", "--exact-match", "HEAD"], cwd)
    # A shallow CI checkout of a tag push may carry no tag objects, so the
    # workflow's own ref counts too.
    ci_tag = (env.get("GITHUB_REF_TYPE") == "tag"
              and env.get("GITHUB_REF_NAME") == tag)
    release = (exact == tag or ci_tag) and not dirty
    return BuildInfo(commit, dirty, release)


def write_stamp(version: str, path: Path | None = None, cwd: Path = _REPO_ROOT) -> BuildInfo:
    """Record this checkout's identity for a frozen build. Called by the spec."""
    info = from_git(version, cwd)
    path = path or (_REPO_ROOT / "src" / f"{STAMP_MODULE}.py")
    path.write_text(
        "# Generated by build_info.write_stamp() at build time. Do not commit.\n"
        f"COMMIT = {info.commit!r}\n"
        f"DIRTY = {info.dirty!r}\n"
        f"RELEASE = {info.release!r}\n",
        encoding="utf-8",
    )
    return info


_cached: BuildInfo | None = None


def current(version: str) -> BuildInfo:
    """This running copy's identity: the stamp when frozen, git from source.

    A frozen build without a stamp (built by a spec that predates this) is
    reported as an unknown dev build. A stale stamp left in src/ is ignored
    from source, where git is the truth.
    """
    global _cached
    if _cached is not None:
        return _cached
    if getattr(sys, "frozen", False):
        try:
            stamp = __import__(STAMP_MODULE)
            _cached = BuildInfo(getattr(stamp, "COMMIT", None),
                                bool(getattr(stamp, "DIRTY", False)),
                                bool(getattr(stamp, "RELEASE", False)))
        except ImportError:
            _cached = BuildInfo(None, False, False)
    else:
        _cached = from_git(version)
    return _cached
